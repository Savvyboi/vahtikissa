import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {filterResearchSpeeches,researchSummary} from '../speech-research.js';
import {decodeSpeechSearchIndex} from '../app-utils.js';

export async function checkResearch(page,navigate,data,audit) {
  const clouds=JSON.parse(await readFile(new URL('../data/speech-wordclouds.json',import.meta.url),'utf8'));
  const profiles=JSON.parse(await readFile(new URL('../data/member-profiles.json',import.meta.url),'utf8'));
  const member=data.members.find(m=>profiles.members[m.id]?.committees.length&&clouds.members[m.id]?.terms.length);
  await navigate('members/'+member.id);
  await page.locator('[data-wordcloud][aria-busy="false"]').waitFor();
  await page.locator('[data-member-profile][aria-busy="false"]').waitFor();
  assert.equal(await page.locator('.wordcloud a').count(),clouds.members[member.id].terms.length);
  assert.ok((await page.locator('.member-profile').innerText()).includes(profiles.members[member.id].occupation.fi));
  assert.equal(await page.locator('.member-profile a[href="'+profiles.members[member.id].pageUrl+'"]').count(),1);
  assert.ok(await page.locator('.member-avatar img').isVisible());
  const cloudBox=await page.locator('[data-wordcloud]').boundingBox(),summaryBox=await page.locator('.member-summary').boundingBox();
  assert.ok(cloudBox.width<=340 && cloudBox.y>=summaryBox.y+summaryBox.height,'Vocabulary is a compact card below the activity summary');
  assert.equal(await page.locator('.wordcloud li:not([hidden])').count(),Math.min(24,clouds.members[member.id].terms.length));
  if(clouds.members[member.id].terms.length>24){
    await page.locator('[data-cloud-expand]').click();
    assert.equal(await page.locator('.wordcloud li:not([hidden])').count(),clouds.members[member.id].terms.length);
    await page.locator('[data-cloud-expand]').click();
    assert.equal(await page.locator('.wordcloud li:not([hidden])').count(),24);
  }
  await page.locator('[data-member-jump="member-about"]').click();
  assert.equal(await page.locator('#member-about').evaluate(el=>el===document.activeElement),true);
  assert.ok(page.url().endsWith('#/members/'+member.id));
  await page.locator('[data-wordcloud] details summary').click();
  const wordDownloadPromise=page.waitForEvent('download');
  await page.locator('[data-export-key="wordcloud"][data-export-format="json"]').click();
  const wordDownload=await wordDownloadPromise,wordRows=JSON.parse(await readFile(await wordDownload.path(),'utf8'));
  assert.equal(wordRows.length,clouds.members[member.id].terms.length);
  assert.ok(wordRows.every(term=>term.count>0&&term.score>0&&term.relativeFrequency>=1.25&&term.ranking===clouds.method.ranking));
  await page.locator('[data-wordcloud] details summary').click();
  const firstTerm=clouds.members[member.id].terms[0];
  await page.locator('.wordcloud a').first().click();
  await page.waitForFunction(()=>document.querySelector('[data-speech-member]')?.value&&document.querySelector('[data-filter]')?.getAttribute('aria-busy')==='false'&&document.querySelector('[data-research-summary] h2'));
  assert.equal(await page.locator('[data-filter]').inputValue(),firstTerm.word);
  assert.equal(await page.locator('[data-speech-member]').inputValue(),member.id);
  assert.equal(await page.locator('[data-speech-match]').inputValue(),'word');
  assert.equal(await page.locator('[data-speech-scope]').inputValue(),'text');
  const textsArray=decodeSpeechSearchIndex(JSON.parse(await readFile(new URL('../data/speech-search.json',import.meta.url),'utf8')));
  const texts=Object.fromEntries(data.speeches.map((s,i)=>[s.id,textsArray[i]]));
  const corpus=data.speeches.filter(s=>s.mpId===member.id);
  const matches=filterResearchSpeeches(corpus,texts,{query:firstTerm.word,mode:'word',scope:'text'});
  assert.equal(await page.locator('[data-speech-count]').innerText(),matches.length.toLocaleString('fi-FI')+' puheenvuoroa');
  await page.locator('.concordance mark').first().waitFor();
  assert.equal(await page.locator('.concordance mark').first().innerText(),firstTerm.word);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-export-key="speeches"][data-export-format="json"]').click();
  const download=await downloadPromise,rows=JSON.parse(await readFile(await download.path(),'utf8'));
  assert.equal(rows.length,matches.length);assert.ok(rows.every(row=>row.text&&row.occurrences>0&&row.query===firstTerm.word&&row.matchMode==='word'));
  const monthPromise=page.waitForEvent('download');
  await page.locator('[data-export-key="speech-months"][data-export-format="json"]').click();
  const monthDownload=await monthPromise,months=JSON.parse(await readFile(await monthDownload.path(),'utf8'));
  const report=researchSummary(corpus,texts,firstTerm.word,'word');
  assert.equal(months.reduce((n,row)=>n+row.words,0),report.words);
  assert.equal(months.reduce((n,row)=>n+row.occurrences,0),report.occurrences);
  await page.locator('[data-research-link]').click();
  await page.waitForFunction(()=>document.querySelector('[data-filter]')?.getAttribute('aria-busy')==='false'&&document.querySelector('[data-research-summary] h2'));
  assert.equal(await page.locator('[data-speech-count]').innerText(),matches.length.toLocaleString('fi-FI')+' puheenvuoroa');
  await page.locator('[data-speech-exclude]').fill(firstTerm.word);
  await page.waitForFunction(()=>document.querySelector('[data-speech-count]')?.textContent==='0 puheenvuoroa');
  await page.locator('[data-speech-exclude]').fill('');
  await page.locator('[data-speech-match]').selectOption('phrase');
  const sample=corpus.find(s=>texts[s.id].split(' ').length>8),phrase=texts[sample.id].split(' ').slice(2,7).join(' ');
  await page.locator('[data-filter]').fill(phrase);
  await page.waitForFunction(phrase=>document.querySelector('.concordance mark')?.textContent===phrase,phrase);
  await audit('fi / research phrase / desktop');
  await page.setViewportSize({width:320,height:740});
  await audit('fi / research phrase / 320px');
  await navigate('members/'+member.id);
  await page.locator('[data-member-profile][aria-busy="false"]').waitFor();
  await page.locator('[data-wordcloud][aria-busy="false"]').waitFor();
  const feedBox=await page.locator('.member-feed').boundingBox(),sidebarBox=await page.locator('.member-sidebar').boundingBox();
  assert.ok(sidebarBox.y>=feedBox.y+feedBox.height,'On phones activity appears before the supporting cards');
  await page.locator('[data-member-jump="member-vocabulary"]').click();
  assert.equal(await page.locator('#member-vocabulary').evaluate(el=>el===document.activeElement),true);
  await audit('fi / MP insights / 320px');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.language-button').click();
  await page.locator('[data-member-profile][aria-busy="false"]').waitFor();
  assert.match(await page.locator('.member-profile').innerText(),/Utbildning/);
  await audit('sv / MP insights / desktop');
  await page.locator('.language-button').click();
  await navigate('budget');
  const budget=JSON.parse(await readFile(new URL('../data/budget.json',import.meta.url),'utf8')),latest=budget.years.at(-1);
  assert.equal(await page.locator('.budget-map-key li').count(),latest.expense.length);
  const main=latest.expense.find(item=>item.children?.length);
  await page.locator('.budget-map-key a[href="#/budget/'+latest.year+'/expense/'+main.code+'"]').click();
  assert.ok(await page.locator('.budget-chart-navigation .budget-back').isVisible());
  assert.equal(await page.locator('.budget-map-key li').count(),main.children.length);
  const noSpeeches=data.members.find(m=>!clouds.members[m.id].speeches);
  if(noSpeeches){await navigate('members/'+noSpeeches.id);await page.locator('[data-wordcloud][aria-busy="false"]').waitFor();assert.equal(await page.locator('.wordcloud a').count(),0);}
  await navigate('overview');
  console.log('MP sources, cloud links, phrase search, exclusions, full-text/monthly exports, reproducible links and budget labels passed.');
}
